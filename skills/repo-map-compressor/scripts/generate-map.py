#!/usr/bin/env python3
"""Generate a compact (<1,500-token) .ai/MAP.md index for a repository."""

from __future__ import annotations

import argparse
import os
import re
from pathlib import Path

IGNORE_DIRS = {
    ".git",
    ".ai",
    "node_modules",
    "dist",
    "build",
    "out",
    "target",
    "__pycache__",
    ".venv",
    "venv",
    ".next",
    ".nuxt",
    ".turbo",
    "coverage",
    "vendor",
}

SYMBOL_PATTERNS = {
    ".py": re.compile(r"^(?:def|async def|class)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M),
    ".ts": re.compile(
        r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|class|const|type|interface|enum)\s+([A-Za-z_][A-Za-z0-9_]*)",
        re.M,
    ),
    ".tsx": re.compile(
        r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|class|const|type|interface|enum)\s+([A-Za-z_][A-Za-z0-9_]*)",
        re.M,
    ),
    ".js": re.compile(
        r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|class|const)\s+([A-Za-z_][A-Za-z0-9_]*)",
        re.M,
    ),
    ".go": re.compile(r"^(?:func|type)\s+([A-Z][A-Za-z0-9_]*)", re.M),
    ".rs": re.compile(r"^pub\s+(?:async\s+)?(?:fn|struct|enum|trait|mod)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M),
    ".sh": re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*\(\)\s*\{", re.M),
}

MAX_CHARS = 5600


def extract_symbols(path: Path) -> list[str]:
    pat = SYMBOL_PATTERNS.get(path.suffix.lower())
    if not pat:
        return []
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return []
    seen: list[str] = []
    for match in pat.findall(text):
        if match not in seen and not match.startswith("_"):
            seen.append(match)
        if len(seen) >= 8:
            break
    return seen


def build_map(root: Path) -> str:
    lines: list[str] = [
        f"# Repository Map: {root.resolve().name}",
        "",
        "Generated by `repo-map-compressor`. Keep under 1,500 tokens.",
        "",
    ]
    verify_cmd = root / ".ai" / "verify.cmd"
    if verify_cmd.exists():
        cmd = verify_cmd.read_text(encoding="utf-8", errors="ignore").strip().splitlines()[0]
        lines.extend([f"- **Verify:** `{cmd}`", ""])

    lines.append("## Modules & Key Symbols")
    lines.append("")

    entries: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in IGNORE_DIRS and not d.startswith("."))
        rel_dir = Path(dirpath).relative_to(root)
        for fn in sorted(filenames):
            fp = Path(dirpath) / fn
            rel_file = (rel_dir / fn).as_posix()
            if fp.suffix.lower() in SYMBOL_PATTERNS:
                syms = extract_symbols(fp)
                if syms:
                    entries.append(f"- `{rel_file}`: {', '.join(syms)}")
                elif rel_dir == Path("."):
                    entries.append(f"- `{rel_file}`")
            elif fn in {"README.md", "package.json", "pyproject.toml", "Cargo.toml", "go.mod"}:
                entries.append(f"- `{rel_file}`")

    budget = MAX_CHARS - len("\n".join(lines)) - 80
    used = 0
    truncated = 0
    for entry in entries:
        if used + len(entry) + 1 > budget:
            truncated += 1
            continue
        lines.append(entry)
        used += len(entry) + 1

    if truncated:
        lines.append(f"- ... ({truncated} additional files omitted to stay within token budget)")

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate compressed .ai/MAP.md repository index.")
    parser.add_argument("repo", nargs="?", default=".", help="Repository root path")
    parser.add_argument("--out", default=".ai/MAP.md", help="Output file path relative to repo or absolute")
    args = parser.parse_args()

    root = Path(args.repo).resolve()
    out_path = Path(args.out)
    if not out_path.is_absolute():
        out_path = root / out_path
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_map(root), encoding="utf-8", newline="\n")
    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
